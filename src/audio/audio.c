/* One backend, one rate: sounds are converted to mono float at this rate when
 * loaded, so the audio thread only ever copies samples. 48 kHz matches the
 * device format on this machine; SDL converts if a device wants something
 * else, which is a load-free operation inside the stream. */
#define AUDIO_RATE 48000
#define AUDIO_CHANNELS 2

/* Largest block the mixer renders per callback. The device may ask for more;
 * supplying less is legal and it will ask again. */
#define AUDIO_SCRATCH_FRAMES 2048

/* A sound fades to silence at this fraction of the screen diagonal. Anything
 * on screen is audible, anything just off it fades out. Relative to the
 * viewport so a resized window does not change the mix; the value only
 * changes loudness, never the simulation. */
#define AUDIO_FALLOFF_FRACTION 0.55f

/* Two events that map to the same slot closer together than this collapse to
 * one voice. A shotgun-style blast (grenade/rocket hits N zombies in one
 * frame) would otherwise sum N copies of the same sample and clip; separate
 * shots are >= 200 ms apart in the sim, so they never collapse. */
#define AUDIO_MIN_INTERVAL 0.03

/* Slot -> file under assets/. Generated by tools/gen_audio.py (deterministic,
 * 48 kHz mono 16-bit); an artist can replace a file 1:1 without touching this
 * table. A NULL path or a missing file is silence, never an error. */
